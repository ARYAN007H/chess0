/**
 * Texel tuning corpus generator (run with `npx tsx scripts/gen-corpus.ts`).
 *
 * Plays v3-vs-v3 self-play games at fixed shallow depth from book openings,
 * records quiet positions (side to move not in check) with the final game
 * result as the target, and writes `fen <wdl>` lines to data/tuning-corpus.txt.
 *
 *   npx tsx scripts/gen-corpus.ts [--games 1000] [--depth 5] [--out data/tuning-corpus.txt]
 */

import { newStartPosition, parseFen, makeMove } from '../src/engine/position';
import type { Position } from '../src/engine/position';
import { insufficientMaterial } from '../src/engine/eval';
import { Engine } from '../src/engine/engine';
import { legalMoves, inCheckOf } from '../src/engine/movegen';
import { probeBookV3 } from '../src/engine/bookV3';
import { searchPositionV3 } from '../src/engine/searchV3';
import { moveToUci } from '../src/engine/types';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { dirname } from 'node:path';

const arg = (name: string, def: number): number => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] ? Number(process.argv[i + 1]) : def;
};
const GAMES = Math.max(1, arg('games', 1000));
const DEPTH = Math.max(2, arg('depth', 5));
const OUT = (() => {
  const i = process.argv.indexOf('--out');
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : 'data/tuning-corpus.txt';
})();
// Optional champion params: corpus is generated by the current best engine so
// the tuning signal compounds across improvement cycles.
const PARAMS = (() => {
  const i = process.argv.indexOf('--params');
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : null;
})();
const MAX_PLIES = 160;
const ADJUDICATE_CP = 350; // |eval| beyond this at the ply cap decides the game

if (PARAMS) {
  const { applyEvalParams, evalV3Params } = await import('../src/engine/evalV3Params');
  const { clearEvalCaches } = await import('../src/engine/evalV3');
  const raw = JSON.parse(readFileSync(PARAMS, 'utf8')) as {
    scalars: Record<string, number>;
    tables: Record<string, number[]>;
  };
  applyEvalParams(raw.scalars as Partial<Record<keyof typeof evalV3Params, number>>, raw.tables);
  clearEvalCaches();
  console.log(`corpus generator: playing with params from ${PARAMS}`);
}

let seed = (Date.now() & 0x7fffffff) | 1;
const rnd = () => {
  seed ^= seed << 13; seed |= 0;
  seed ^= seed >>> 17;
  seed ^= seed << 5; seed |= 0;
  return (seed >>> 0) / 4294967296;
};

function sampleOpening(plies: number): string[] {
  const pos = newStartPosition();
  const uci: string[] = [];
  for (let i = 0; i < plies; i++) {
    const candidates = probeBookV3(pos);
    if (candidates.length === 0) break;
    let total = 0;
    for (const c of candidates) total += c.weight;
    let roll = Math.random() * total;
    let picked = candidates[candidates.length - 1];
    for (const c of candidates) {
      roll -= c.weight;
      if (roll <= 0) { picked = c; break; }
    }
    uci.push(picked.uci);
    const eng = new Engine();
    eng.pos = pos;
    const m = eng.uciToMove(picked.uci);
    if (m === null) break;
    eng.applyMove(m);
  }
  return uci;
}

interface Recorded { fen: string; wdl: number }

function playGame(): Recorded[] {
  const pos = newStartPosition();
  for (const uci of sampleOpening(6)) {
    const eng = new Engine();
    eng.pos = pos;
    const m = eng.uciToMove(uci);
    if (m === null) break;
    eng.applyMove(m);
  }

  const recorded: Recorded[] = [];
  const repKeys = new Map<string, number>();
  let result: number | null = null; // white-POV wdl

  for (let ply = 0; ply < MAX_PLIES; ply++) {
    const moves = legalMoves(pos);
    if (moves.length === 0) {
      result = inCheckOf(pos, pos.stm) ? (pos.stm === 0 ? 0 : 1) : 0.5;
      break;
    }
    if (insufficientMaterial(pos)) { result = 0.5; break; }
    if (pos.halfmove >= 100) { result = 0.5; break; }

    const key = `${pos.hashLo},${pos.hashHi}`;
    const seen = (repKeys.get(key) ?? 0) + 1;
    repKeys.set(key, seen);
    if (seen >= 3) { result = 0.5; break; }

    // Record quiet positions with some context
    if (ply >= 8 && !inCheckOf(pos, pos.stm)) {
      recorded.push({ fen: toFenLine(pos), wdl: -1 }); // wdl filled after the game
    }

    const r = searchPositionV3(pos, { depth: DEPTH });
    const eng = new Engine();
    eng.pos = pos;
    const m = eng.uciToMove(r.bestMoveUci);
    if (m === null) break;
    makeMove(pos, m);
  }

  if (result === null) {
    // Adjudicate by eval sign at the cap (both sides played the same engine)
    const e = searchPositionV3(pos, { depth: DEPTH }).scoreCp ?? 0;
    const stmSign = pos.stm === 0 ? 1 : -1;
    const whiteCp = e * stmSign;
    result = whiteCp > ADJUDICATE_CP ? 1 : whiteCp < -ADJUDICATE_CP ? 0 : 0.5;
  }

  for (const rec of recorded) rec.wdl = result;
  return recorded;
}

function toFenLine(pos: Position): string {
  const eng = new Engine();
  eng.pos = pos;
  return eng.fen();
}

const t0 = Date.now();
const lines: string[] = [];
for (let g = 1; g <= GAMES; g++) {
  const recs = playGame();
  for (const r of recs) lines.push(`${r.fen} ${r.wdl}`);
  if (g % 100 === 0) {
    const rate = (Date.now() - t0) / 1000 / g;
    console.log(`game ${g}/${GAMES}  positions=${lines.length}  ${rate.toFixed(2)}s/game  eta ${((GAMES - g) * rate / 60).toFixed(1)}min`);
  }
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`\nwrote ${lines.length} positions -> ${OUT} (${((Date.now() - t0) / 60000).toFixed(1)} min)`);
