/**
 * Rebuilds the WASM SIMD kernel and emits it as a base64 TS module.
 *
 *   npx tsx scripts/build-nnue-wasm.ts
 *
 * Requires: rustup with the wasm32-unknown-unknown target. The generated
 * module (src/engine/nnueSimdWasmB64.ts) is committed, so non-Rust
 * environments never need cargo.
 */

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const crate = join(root, 'wasm', 'nnue-simd');
const wasmPath = join(crate, 'target', 'wasm32-unknown-unknown', 'release', 'nnue_simd.wasm');
const outPath = join(root, 'src', 'engine', 'nnueSimdWasmB64.ts');

if (!existsSync(wasmPath)) {
  console.log('building wasm/nnue-simd (release, wasm32-unknown-unknown)...');
  const env = { ...process.env, PATH: `${process.env.HOME}/.cargo/bin:${process.env.PATH}` };
  execSync('cargo build --release', { cwd: crate, stdio: 'inherit', env });
}
const bytes = readFileSync(wasmPath);
const b64 = bytes.toString('base64');
writeFileSync(
  outPath,
  `/**
 * GENERATED by scripts/build-nnue-wasm.ts from wasm/nnue-simd/src/lib.rs —
 * do not edit by hand. Source of truth: the Rust crate; rebuild with
 * \`npx tsx scripts/build-nnue-wasm.ts\`.
 *
 * Layer-2/3 WASM SIMD kernel (wasm32-unknown-unknown, simd128), embedded as
 * base64 so Node (gates/tests) and the browser bundle load the identical
 * module with zero bundler configuration.
 */
export const NNUE_SIMD_WASM_B64 = '${b64}';
`,
);
console.log(`wrote ${outPath} (${bytes.length}B wasm → ${b64.length}B base64)`);
