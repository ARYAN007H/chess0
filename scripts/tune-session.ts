/**
 * Champion/challenger tuning session driver (used by .github/workflows/tune.yml
 * and runnable locally: `npx tsx scripts/tune-session.ts --cycles 3`).
 *
 * Each cycle:
 *   1. Generate a fresh self-play corpus with the CURRENT CHAMPION params.
 *   2. Tune a challenger starting from the champion (validation early-stopping).
 *   3. Gate: challenger vs champion in a real played match. By default this is
 *      a trinomial SPRT (H0 = 0 Elo, H1 = +30 Elo); the champion is replaced
 *      ONLY on SPRT ACCEPT. `--no-sprt` restores the old fixed-score bar.
 *   4. On acceptance, data/params-current.json is updated and committed, and
 *      data/artifacts/accepted-<engine>.json is written for the workflow's
 *      post-push verification.
 *
 * All artifacts (corpora, challenger params, match logs) land in data/artifacts/
 * for upload by the workflow.
 */

import { spawnSync } from 'node:child_process';
import { writeFileSync, mkdirSync, existsSync, copyFileSync, unlinkSync } from 'node:fs';

const arg = (name: string, def: number): number => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] ? Number(process.argv[i + 1]) : def;
};
const CYCLES = arg('cycles', 3);
const CORPUS_GAMES = arg('corpus-games', 3000);
const CORPUS_DEPTH = arg('corpus-depth', 5);
const SWEEPS = arg('sweeps', 8);
const MATCH_PAIRS = arg('match-pairs', 300); // 2x pairs games: SPRT max, not a fixed count
const MOVETIME = arg('movetime', 200);
const ACCEPT_MIN_SCORE = arg('accept-score', 60); // legacy --no-sprt gate only
const SPRT = !process.argv.includes('--no-sprt');
const SPRT_ELO0 = arg('sprt-elo0', 0);
const SPRT_ELO1 = arg('sprt-elo1', 30);
const SPRT_ALPHA = arg('alpha', 0.05);
const SPRT_BETA = arg('beta', 0.1);
// Workflow mode: corpus shards were generated by parallel matrix jobs and
// merged; --corpus skips generation and uses the merged file for ALL cycles.
const PRESET_CORPUS = (() => {
  const i = process.argv.indexOf('--corpus');
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : null;
})();

const CHAMPION = 'data/params-current.json';
const CHALLENGER = 'data/tuned-params.json';
const ARTIFACTS = 'data/artifacts';
mkdirSync(ARTIFACTS, { recursive: true });
// Which engine this session tunes (v3 flagship by default). v2 gets its own
// nightly session with its own champion file.
const ENGINE = (() => {
  const i = process.argv.indexOf('--engine');
  const v = i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : 'v3';
  if (v !== 'v3' && v !== 'v2') throw new Error(`--engine must be v3|v2, got ${v}`);
  return v;
})();
const CHAMPION_FILE = ENGINE === 'v3' ? 'data/params-current.json' : 'data/params-current-v2.json';
const TUNED_FILE = ENGINE === 'v3' ? 'data/tuned-params.json' : 'data/tuned-params-v2.json';
const GATE_A = ENGINE === 'v3' ? 'v3base' : 'v2base';
const GATE_B = ENGINE === 'v3' ? 'v3tuned' : 'v2tuned';
const ACCEPT_MARKER = `${ARTIFACTS}/accepted-${ENGINE}.json`;
// v3 games are more decisive; v2 draws roughly 70-80% of the time. The SPRT
// trinomial model uses this only to split score into implied W/L, so a wrong
// assumption changes efficiency, not the direction of the test.
const SPRT_DRAW_RATE = arg('draw-rate', ENGINE === 'v3' ? 0.5 : 0.7);
const WALL_BUDGET_MIN = arg('wall-budget-min', 200); // gate hard stop, min (job cap 330)

// A stale marker from a previous local run must not make the workflow think
// this cycle accepted a challenger.
try {
  unlinkSync(ACCEPT_MARKER);
} catch {
  /* no stale marker */
}

if (!existsSync(CHAMPION_FILE)) {
  writeFileSync(
    CHAMPION_FILE,
    JSON.stringify({ note: `factory defaults (see src/engine/evalV${ENGINE === 'v3' ? '3' : '2'}Params.ts)`, scalars: {}, tables: {} }, null, 2) + '\n',
  );
  console.log(`seeded ${CHAMPION_FILE} with factory defaults`);
}

interface ApplyShape {
  scalars: Record<string, number>;
  tables: Record<string, number[]>;
}

function run(cmd: string, args: string[], label: string): string {
  console.log(`\n=== ${label}: ${cmd} ${args.join(' ')}`);
  const t0 = Date.now();
  const res = spawnSync('npx', ['tsx', cmd, ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  const out = (res.stdout ?? '') + (res.stderr ?? '');
  process.stdout.write(out.slice(-4000));
  console.log(`(${((Date.now() - t0) / 60000).toFixed(1)} min, exit ${res.status})`);
  if (res.status !== 0) throw new Error(`${label} failed with exit ${res.status}`);
  return out;
}

let accepted = 0;
for (let cycle = 1; cycle <= CYCLES; cycle++) {
  console.log(`\n########## CYCLE ${cycle}/${CYCLES} ##########`);

  let corpus: string;
  if (PRESET_CORPUS) {
    corpus = PRESET_CORPUS;
    console.log(`using preset corpus ${corpus} (generated by parallel matrix jobs)`);
  } else {
    corpus = `${ARTIFACTS}/corpus-${ENGINE}-${cycle}.txt`;
    run('scripts/gen-corpus.ts', ['--engine', ENGINE, '--games', String(CORPUS_GAMES), '--depth', String(CORPUS_DEPTH), '--out', corpus, '--params', CHAMPION_FILE], `cycle ${cycle} corpus`);
  }

  run('scripts/texel-tune.ts', ['--eval', ENGINE, '--corpus', corpus, '--base', CHAMPION_FILE, '--sweeps', String(SWEEPS)], `cycle ${cycle} tune`);
  copyFileSync(TUNED_FILE, `${ARTIFACTS}/challenger-${ENGINE}-${cycle}.json`);

  const gateArgs = [
    '--a', GATE_A,
    '--b', GATE_B,
    '--pairs', String(MATCH_PAIRS),
    '--movetime', String(MOVETIME),
  ];
  if (SPRT) {
    gateArgs.push(
      '--sprt',
      '--sprt-elo0', String(SPRT_ELO0),
      '--sprt-elo1', String(SPRT_ELO1),
      '--alpha', String(SPRT_ALPHA),
      '--beta', String(SPRT_BETA),
      '--draw-rate', String(SPRT_DRAW_RATE),
      '--wall-budget-min', String(WALL_BUDGET_MIN),
    );
  }
  const matchOut = run('scripts/match.ts', gateArgs, `cycle ${cycle} gate`);
  writeFileSync(`${ARTIFACTS}/gate-${ENGINE}-${cycle}.log`, matchOut);

  // Parse the challenger's counts for human logs, and the explicit SPRT
  // verdict for the promotion decision.
  const m = matchOut.match(new RegExp(`${GATE_B}: (\\d+)W (\\d+)D (\\d+)L`));
  let scorePct = 50;
  if (m) {
    const [w, d] = [Number(m[1]), Number(m[2])];
    const n = Number(m[1]) + Number(m[2]) + Number(m[3]);
    scorePct = (100 * (w + 0.5 * d)) / Math.max(1, n);
  }
  const sprtMatch = matchOut.match(/SPRT: (ACCEPT|REJECT|INCONCLUSIVE)/);
  const sprtVerdict = sprtMatch?.[1] ?? null;
  const acceptedThis = SPRT ? sprtVerdict === 'ACCEPT' : scorePct > ACCEPT_MIN_SCORE;
  const verdict = SPRT
    ? `SPRT ${sprtVerdict ?? 'MISSING'} (scored ${scorePct.toFixed(1)}%)`
    : `scored ${scorePct.toFixed(1)}% (accept > ${ACCEPT_MIN_SCORE}%)`;
  console.log(`\nCYCLE ${cycle} GATE: ${verdict} -> ${acceptedThis ? 'ACCEPT' : 'DISCARD'}`);

  if (acceptedThis) {
    writeFileSync(
      ACCEPT_MARKER,
      JSON.stringify(
        {
          engine: ENGINE,
          cycle,
          scorePct,
          sprt: sprtVerdict,
          matchPairs: MATCH_PAIRS,
          movetime: MOVETIME,
          timestamp: new Date().toISOString(),
        },
        null,
        2,
      ) + '\n',
    );
    copyFileSync(TUNED_FILE, CHAMPION_FILE);
    accepted++;
    try {
      spawnSync('git', ['add', CHAMPION_FILE], { encoding: 'utf8' });
      const c = spawnSync(
        'git',
        ['commit', '-m', `tune(${ENGINE}): accept cycle ${cycle} challenger (${verdict}, ${MOVETIME}ms)`],
        { encoding: 'utf8' },
      );
      if (c.status === 0) console.log(`committed new champion (${CHAMPION_FILE})`);
      else console.error(`WARNING: champion commit failed (exit ${c.status}): ${(c.stderr || '').trim()} — champion file is updated on disk; the workflow push step will publish it`);
    } catch {
      /* local runs without git: keep going */
    }
  } else {
    // Restore the challenger file to the champion so the next cycle starts clean.
    copyFileSync(CHAMPION_FILE, TUNED_FILE);
  }
}

console.log(`\n########## ${ENGINE.toUpperCase()} SESSION DONE: ${accepted}/${CYCLES} cycles accepted ##########`);
